import fs from 'node:fs';
import assert from 'node:assert/strict';
const source = fs.readFileSync(new URL('../web/model.js', import.meta.url), 'utf8');
const {DropdownController:C, PresetStore, normalize} = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
let before=0,after=0;
const node={properties:{},graph:{beforeChange(){before++},afterChange(){after++}},setDirtyCanvas(){}};
const selected={value:'B'},entries={value:'A\nB'},mode={value:'manual'};
const c=new C(node,selected,entries,mode);c.sync();assert.equal(selected.value,'legacy-1');
c.edit('legacy-1',{label:'Renamed',value:'multi\nline'});assert.equal(selected.value,'legacy-1');
c.move('legacy-1',-1);assert.equal(c.items[0].label,'Renamed');
c.undo();assert.equal(c.items[1].label,'Renamed');c.redo();assert.equal(c.items[0].label,'Renamed');
c.remove('legacy-1');assert.equal(c.items.length,1);c.undo();assert.equal(selected.value,'legacy-1');
c.settings.loop=false;c.step(-1);assert.equal(selected.value,'legacy-1');c.settings.loop=true;c.step(-1);assert.equal(selected.value,'legacy-0');
c.query='MULTI';assert.equal(c.matches().length,1);
const exported=c.export();c.import('new\nentries');c.undo();assert.equal(c.export(),exported);
const snapshot=c.snapshot();assert.throws(()=>c.import('{"version":99,"items":[]}'));assert.equal(c.snapshot(),snapshot);
assert.throws(()=>c.edit('legacy-1',{label:''}));assert.equal(c.snapshot(),snapshot);
const map=new Map(),store=new PresetStore({getItem:k=>map.get(k),setItem:(k,v)=>map.set(k,v)});
store.save('__proto__',c.items);assert.equal(Object.hasOwn(store.read(),'__proto__'),true);store.remove('__proto__');assert.equal(Object.keys(store.read()).length,0);
store.save('Test',c.items);assert.equal(store.read().Test.length,2);
assert.throws(()=>normalize({version:2,items:[{id:'a',label:'A',value:''},{id:'a',label:'B',value:''}]}));
const copy=new C({properties:JSON.parse(JSON.stringify(node.properties)),setDirtyCanvas(){}},{value:selected.value},{value:entries.value},{value:mode.value});copy.sync();assert.equal(copy.export(),c.export());
assert.equal(before,after);console.log('Model, undo, import, presets, migration and duplication checks passed');
